#!/bin/bash
# Write a Meson cross file for the selected AROS_TARGET into stdout, or
# into the path given as $1. Paths come from env.sh; this file is not
# a stored machine configuration.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=env.sh
source "$SCRIPT_DIR/env.sh"
require_aros_toolchain
# shellcheck source=toolwrap.sh
source "$SCRIPT_DIR/toolwrap.sh"

OUT="${1:-}"

# Mainline: the compiler's built-in sysroot is whatever tree it was built
# beside, so headers and the startup code must come from AROS_SDK by name.
# Without this the program is compiled and linked against that other tree.
SYSROOT_ARG=
[ "$AROS_TARGET" = mainline ] && SYSROOT_ARG="'--sysroot=${AROS_SDK}', "

content() {
  cat <<EOF
# Generated by scripts/write-meson-cross.sh for AROS_TARGET=$AROS_TARGET.
# Do not edit; regenerate.

[binaries]
c = '${AROS_CC_WRAPPED}'
cpp = '${AROS_CXX_WRAPPED}'
ar = '${AROS_AR}'
strip = '${AROS_STRIP}'
pkg-config = 'pkg-config'

[host_machine]
system = 'aros'
cpu_family = '${AROS_CPU}'
cpu = '${AROS_CPU}'
endian = 'little'

[properties]
pkg_config_libdir = '${DEPS_DIR}/lib/pkgconfig'

[built-in options]
default_library = 'static'
c_std = 'gnu11'
b_staticpic = false
b_pie = false
c_args = [${SYSROOT_ARG}'-fno-pic', '-fno-PIC']
cpp_args = [${SYSROOT_ARG}'-fno-pic', '-fno-PIC']
c_link_args = [${SYSROOT_ARG}'-L${AROS_SDK}/lib']
cpp_link_args = [${SYSROOT_ARG}'-L${AROS_SDK}/lib']
EOF
}

if [ -z "$OUT" ]; then
  content
else
  mkdir -p "$(dirname "$OUT")"
  content > "$OUT"
  echo "wrote $OUT (AROS_TARGET=$AROS_TARGET)"
fi
