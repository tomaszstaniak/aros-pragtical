#!/usr/bin/env python3
"""Compile contrib's SDL3-aros-staticlib file list with the AROS toolchain.

Same recipe as aros-openloco/scripts/build-sdl3.py: read FILES from
contrib mmakefile.src, build libSDL3_static.a, install headers, and
write CMake plus pkg-config so Meson can find SDL3.
"""
import argparse
import datetime
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--deps", required=True)
ap.add_argument("--sdl3-ver", required=True)
ap.add_argument("--cc", required=True)
ap.add_argument("--ar", required=True)
ap.add_argument("--sdk", required=True)
ap.add_argument("--build", required=True)
a = ap.parse_args()

deps = Path(a.deps)
prefix = deps
src = deps / f"src/SDL3-{a.sdl3_ver}"
cc = Path(a.cc)
ar = Path(a.ar)
sdk = Path(a.sdk)
# Mainline intentionally keeps libiconv outside the base SDK; ABIv11 may
# install it directly. Select a complete header/library pair from this SDK.
iconv = next((root for root in (sdk, sdk / "SDK/Extras")
              if (root / "include/iconv.h").is_file()
              and (root / "lib/libiconv.a").is_file()), None)
# The Raspberry Pi SDK has no libiconv. SDL3 then uses its own converter:
# the configuration header enables HAVE_ICONV only when iconv.h is found.

mm = (deps / "src/contrib-sdl3/mmakefile.src").read_text()
block = []
lines = mm.splitlines()
for i, ln in enumerate(lines):
    if re.match(r"FILES\s*[:+]?=", ln):
        for cont in lines[i:]:
            block.append(cont)
            if not cont.rstrip().endswith("\\"):
                break
files = re.findall(r"\$\(ARCHSRCDIR\)/(\S+)", "\n".join(block))
assert len(files) > 150, f"only {len(files)} files parsed from mmakefile.src"

objdir = Path(a.build) / "sdl3"
objdir.mkdir(parents=True, exist_ok=True)
adate = datetime.date.today().strftime("%d.%m.%Y")

INCLUDES = [
    f"-I{src}/include",
    f"-I{src}/include/build_config",
    f"-I{src}",
    f"-I{src}/src",
    f"-I{sdk}/include",
]
if iconv is not None:
    INCLUDES.append(f"-I{iconv}/include")
iconv_lib = f";{iconv / 'lib' / 'libiconv.a'}" if iconv is not None else ""
iconv_flags = f" -L{iconv}/lib -liconv" if iconv is not None else ""
NO_ICONV = [] if iconv is not None else ["-DSDL_AROS_NO_ICONV"]
CFLAGS = [
    "-std=gnu99",
    "-O2",
    "-DSDL3_AROS_STATIC",
    f'-DADATE="{adate}"',
    "-Wno-stringop-truncation",
    "-w",
    # Keep the build machine's directory names out of __FILE__ strings.
    f"-ffile-prefix-map={src}=SDL3-{a.sdl3_ver}",
]

units = [(src / (f + ".c"), objdir / (f.replace("/", "_") + ".o")) for f in files]
units.append((deps / "src/contrib-sdl3/SDL3_static.c", objdir / "SDL3_static.o"))


def build(u):
    s, o = u
    if not s.exists():
        return s, 127, f"missing source {s}"
    r = subprocess.run(
        [str(cc), f"--sysroot={sdk}"] + CFLAGS + NO_ICONV + INCLUDES + ["-c", str(s), "-o", str(o)],
        capture_output=True,
        text=True,
    )
    return s, r.returncode, r.stdout + r.stderr


fail = 0
with ThreadPoolExecutor(max_workers=8) as ex:
    for s, rc, out in ex.map(build, units):
        if rc != 0:
            fail += 1
            print(f"FAIL {s.name}\n{out[:600]}", file=sys.stderr)

print(f"compiled {len(units) - fail}/{len(units)} objects")
if fail:
    sys.exit(1)

(prefix / "lib").mkdir(parents=True, exist_ok=True)
lib = prefix / "lib/libSDL3_static.a"
lib.unlink(missing_ok=True)
objs = [str(o) for _, o in units]
for i in range(0, len(objs), 100):
    subprocess.run([str(ar), "rcs", str(lib)] + objs[i : i + 100], check=True)

incdst = prefix / "include/SDL3"
incdst.mkdir(parents=True, exist_ok=True)
for h in (src / "include/SDL3").glob("*.h"):
    (incdst / h.name).write_bytes(h.read_bytes())

cfgdir = prefix / "lib/cmake/SDL3"
cfgdir.mkdir(parents=True, exist_ok=True)
(cfgdir / "SDL3Config.cmake").write_text(
    f"""# Generated by scripts/build-sdl3.py - do not edit.
if(NOT TARGET SDL3::SDL3)
    add_library(SDL3::SDL3 STATIC IMPORTED)
    set_target_properties(SDL3::SDL3 PROPERTIES
        IMPORTED_LOCATION "{lib}"
        INTERFACE_INCLUDE_DIRECTORIES "{prefix / "include"}"
        INTERFACE_LINK_LIBRARIES "{sdk / 'lib' / 'libGL.a'}{iconv_lib};pthread;m")
endif()
if(NOT TARGET SDL3::SDL3-static)
    add_library(SDL3::SDL3-static ALIAS SDL3::SDL3)
endif()
if(NOT TARGET SDL3::Headers)
    add_library(SDL3::Headers ALIAS SDL3::SDL3)
endif()
set(SDL3_FOUND TRUE)
"""
)
(cfgdir / "SDL3ConfigVersion.cmake").write_text(
    f"""set(PACKAGE_VERSION "{a.sdl3_ver}")
if(PACKAGE_FIND_VERSION VERSION_GREATER PACKAGE_VERSION)
    set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
    set(PACKAGE_VERSION_COMPATIBLE TRUE)
    set(PACKAGE_VERSION_EXACT TRUE)
endif()
"""
)

pcdir = prefix / "lib/pkgconfig"
pcdir.mkdir(parents=True, exist_ok=True)
(pcdir / "sdl3.pc").write_text(
    f"""prefix={prefix}
libdir=${{prefix}}/lib
includedir=${{prefix}}/include

Name: sdl3
Description: Simple DirectMedia Layer (AROS static {a.sdl3_ver})
Version: {a.sdl3_ver}
Libs: -L${{libdir}} -L{sdk}/lib -lSDL3_static -lGL{iconv_flags} -lpthread -lm
Cflags: -I${{includedir}}
"""
)

print(f"{lib} ({lib.stat().st_size // 1024} KiB)")
print(f"headers in {incdst}")
print(f"cmake package in {cfgdir}")
print(f"pkg-config in {pcdir / 'sdl3.pc'}")
